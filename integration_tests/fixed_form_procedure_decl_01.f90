      MODULE FIXED_FORM_PROCEDURE_DECL_01_M
      IMPLICIT NONE
      ABSTRACT INTERFACE
      SUBROUTINE IFACE(X)
      INTEGER, INTENT(INOUT) :: X
      END SUBROUTINE
      END INTERFACE
      PROCEDURE(IFACE), POINTER :: MP => NULL()
      CONTAINS
      SUBROUTINE ADD1(X)
      INTEGER, INTENT(INOUT) :: X
      X = X + 1
      END SUBROUTINE
      SUBROUTINE TWICE(X)
      INTEGER, INTENT(INOUT) :: X
      X = 2*X
      END SUBROUTINE
      SUBROUTINE CALLA(P, X)
      PROCEDURE(ADD1) :: P
      INTEGER, INTENT(INOUT) :: X
      CALL P(X)
      END SUBROUTINE
      SUBROUTINE CALLI(P, X)
      PROCEDURE(IFACE) P
      INTEGER, INTENT(INOUT) :: X
      CALL P(X)
      END SUBROUTINE
      SUBROUTINE CALLO(X, P)
      INTEGER, INTENT(INOUT) :: X
      PROCEDURE(IFACE), OPTIONAL :: P
      IF (PRESENT(P)) THEN
          CALL P(X)
      ELSE
          X = -X
      END IF
      END SUBROUTINE
      END MODULE

      PROGRAM FIXED_FORM_PROCEDURE_DECL_01
      USE FIXED_FORM_PROCEDURE_DECL_01_M
      IMPLICIT NONE
      PROCEDURE(IFACE), POINTER :: PP => NULL()
      INTEGER :: I, PROCEDUREX
      PROCEDUREX = 7
      I = 1
      CALL CALLA(ADD1, I)
      IF (I /= 2) ERROR STOP
      CALL CALLI(TWICE, I)
      IF (I /= 4) ERROR STOP
      CALL CALLO(I, ADD1)
      IF (I /= 5) ERROR STOP
      CALL CALLO(I)
      IF (I /= -5) ERROR STOP
      IF (ASSOCIATED(PP)) ERROR STOP
      PP => TWICE
      IF (.NOT. ASSOCIATED(PP)) ERROR STOP
      CALL PP(I)
      IF (I /= -10) ERROR STOP
      MP => ADD1
      CALL MP(I)
      IF (I /= -9) ERROR STOP
      CALL CALLI(PP, I)
      IF (I /= -18) ERROR STOP
      IF (PROCEDUREX /= 7) ERROR STOP
      PRINT *, I
      END PROGRAM
