      MODULE FIXED_FORM_IMPORT_01_M
      INTEGER, PARAMETER :: DP = KIND(1.0D0)
      TYPE PT
          REAL(DP) :: X, Y
      END TYPE
      INTERFACE
      SUBROUTINE SHIFT(P, D)
      IMPORT DP, PT
      TYPE(PT), INTENT(INOUT) :: P
      REAL(DP), INTENT(IN) :: D
      END SUBROUTINE
      FUNCTION NORM1(P)
      IMPORT :: DP, PT
      TYPE(PT), INTENT(IN) :: P
      REAL(DP) :: NORM1
      END FUNCTION
      SUBROUTINE DOUBLE(P)
      IMPORT
      TYPE(PT), INTENT(INOUT) :: P
      END SUBROUTINE
      END INTERFACE
      END MODULE

      SUBROUTINE SHIFT(P, D)
      USE FIXED_FORM_IMPORT_01_M, ONLY: DP, PT
      TYPE(PT), INTENT(INOUT) :: P
      REAL(DP), INTENT(IN) :: D
      P%X = P%X + D
      P%Y = P%Y + D
      END SUBROUTINE

      SUBROUTINE DOUBLE(P)
      USE FIXED_FORM_IMPORT_01_M, ONLY: PT
      TYPE(PT), INTENT(INOUT) :: P
      P%X = 2*P%X
      P%Y = 2*P%Y
      END SUBROUTINE

      FUNCTION NORM1(P)
      USE FIXED_FORM_IMPORT_01_M, ONLY: DP, PT
      TYPE(PT), INTENT(IN) :: P
      REAL(DP) :: NORM1
      NORM1 = ABS(P%X) + ABS(P%Y)
      END FUNCTION

      PROGRAM FIXED_FORM_IMPORT_01
      USE FIXED_FORM_IMPORT_01_M
      TYPE(PT) :: Q
      INTEGER :: IMPORTX, IMPORT
      Q = PT(1.0_DP, -2.0_DP)
      CALL SHIFT(Q, 0.5_DP)
      IF (ABS(Q%X - 1.5_DP) > 1.0E-12_DP) ERROR STOP
      IF (ABS(Q%Y + 1.5_DP) > 1.0E-12_DP) ERROR STOP
      IF (ABS(NORM1(Q) - 3.0_DP) > 1.0E-12_DP) ERROR STOP
      CALL DOUBLE(Q)
      IF (ABS(NORM1(Q) - 6.0_DP) > 1.0E-12_DP) ERROR STOP
      IMPORTX = 1
      IMPORT = 2
      IF (IMPORTX + IMPORT /= 3) ERROR STOP
      PRINT *, NORM1(Q)
      END PROGRAM
