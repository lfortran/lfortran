program array_section_assign_07
use array_section_assign_07_m, only: a, b, d, l, init
implicit none
integer :: i, j
a = 0
b = 0
d = 0
l = .false.
call init()
do i = 1, 24
    do j = 2, 7
        if (a(j, i) /= real(j)) error stop
    end do
    if (mod(i, 2) == 1) then
        if (a(1, i) /= 1. .or. a(8, i) /= 8.) error stop
    else
        if (a(1, i) /= real(i) .or. a(8, i) /= -real(i)) error stop
    end if
end do
do i = 1, 8
    if (any(b(:, i) /= [i, 2, 3, 4])) error stop
    if (any(d(:, i) /= [0.5_8, 1.5_8, i + 0.5_8])) error stop
    if (.not. l(1, i)) error stop
    if (l(2, i) .neqv. mod(i, 2) == 0) error stop
end do
print *, sum(a), sum(b), sum(d)
end program
